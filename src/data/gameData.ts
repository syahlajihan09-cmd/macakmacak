// Generate Level Config for each restaurant
export function getLevelConfig(restaurantId: string, levelNumber: number): LevelConfig {
  const restaurant = RESTAURANTS_LIST.find((r) => r.id === restaurantId) || RESTAURANTS_LIST[0];
  const allIds = restaurant.availableMenus.map((m) => m.id);

  // Progressive menu unlock per level
  const menusAllowedCount = Math.min(allIds.length, Math.max(2, Math.ceil((levelNumber / restaurant.levelsCount) * allIds.length)));
  const allowedMenuIds = allIds.slice(0, menusAllowedCount);

  // Level requirements scale
  const targetCustomers = 4 + levelNumber * 2; // Level 1: 6, Level 5: 14, Level 8: 20
  const targetCoins = targetCustomers * 28;
  const spawnIntervalSeconds = Math.max(3.6, 5.8 - levelNumber * 0.25); // Faster customer arrival at higher levels!

  return {
    levelNumber,
    restaurantId,
    targetCustomers,
    targetCoins,
    maxLostAllowed: 5, // Strictly max 5 customers allowed to leave, 6th loses!
    spawnIntervalSeconds,
    allowedMenuIds,
    starScores: [
      targetCoins,
      Math.round(targetCoins * 1.35),
      Math.round(targetCoins * 1.8),
    ],
  };
}

